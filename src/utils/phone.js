// phone.js — เกณฑ์เบอร์โทรที่ใช้ทั้งแอป (หน้าแจ้งสัตว์จร, โปรไฟล์, ประกาศสัตว์หาย)
//
// เดิมแต่ละหน้าเขียน regex เอง: หน้าแจ้งสัตว์จรรับ 9–10 หลัก แต่โปรไฟล์กับประกาศสัตว์หายบังคับ 10 หลัก
// ผู้ใช้ที่เบอร์ 9 หลักผ่านตอนแจ้ง จึงมาแก้เบอร์ในโปรไฟล์ไม่ได้ — กติกาเดียวที่ใช้คือเบอร์มือถือไทย 10 หลักขึ้นต้น 0

export const รูปแบบเบอร์โทร = /^0[0-9]{9}$/

export const ข้อความเบอร์ไม่ถูกต้อง = 'เบอร์โทรต้องเป็นตัวเลข 10 หลัก ขึ้นต้นด้วย 0 (เช่น 0812345678)'

export function เบอร์ถูกต้อง(เบอร์) {
  return รูปแบบเบอร์โทร.test((เบอร์ || '').trim())
}
