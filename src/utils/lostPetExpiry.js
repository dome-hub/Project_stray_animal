// lostPetExpiry.js — อายุของประกาศตามหาสัตว์เลี้ยง (ตาราง lost_pets)
//
// ประกาศที่ไม่มีวันหมดอายุทำให้แบนเนอร์ "สัตว์หายด่วน" หน้าแรกโชว์ประกาศเก่าเป็นเดือนๆ ต่อไปเรื่อยๆ
// และคนที่พบสัตว์ไปโทรหาเจ้าของที่เจอน้องแล้ว (หรือเลิกตามไปแล้ว) กฎคือ:
//   - ประกาศแสดงต่อสาธารณะ 30 วัน นับจากวันที่ลงประกาศ หรือวันที่เจ้าของกดต่ออายุล่าสุด (renewed_at)
//   - เกินแล้วคนอื่นไม่เห็น เจ้าของยังเห็นของตัวเองพร้อมป้าย "หมดอายุ" และกดต่ออายุ/ปิดประกาศได้
// renewed_at เป็นคอลัมน์ที่เพิ่มด้วย supabase-fix-lost-pets-expiry.sql — ถ้ายังไม่ได้รัน ค่าเป็น undefined
// แล้วจะนับจาก created_at อย่างเดียว (หน้าเว็บไม่พัง แต่ต่ออายุยังไม่ได้)

import { แปลงเป็นDate } from './dateTime'

export const อายุประกาศวัน = 30

const มิลลิวินาทีต่อวัน = 24 * 60 * 60 * 1000

// วันที่เริ่มนับอายุ — ต่ออายุล่าสุด ถ้าไม่เคยต่อก็วันที่ลงประกาศ
function วันเริ่มนับ(โพสต์) {
  return แปลงเป็นDate(โพสต์.renewed_at || โพสต์.created_at)
}

// เหลืออีกกี่วัน (ปัดขึ้น) — ติดลบหรือ 0 = หมดอายุแล้ว
export function วันที่เหลือของประกาศ(โพสต์) {
  const เริ่ม = วันเริ่มนับ(โพสต์).getTime()
  if (Number.isNaN(เริ่ม)) return อายุประกาศวัน   // อ่านวันที่ไม่ได้ → ไม่ซ่อนประกาศทิ้ง
  const หมดเมื่อ = เริ่ม + อายุประกาศวัน * มิลลิวินาทีต่อวัน
  return Math.ceil((หมดเมื่อ - Date.now()) / มิลลิวินาทีต่อวัน)
}

export function ประกาศหมดอายุแล้ว(โพสต์) {
  return วันที่เหลือของประกาศ(โพสต์) <= 0
}
