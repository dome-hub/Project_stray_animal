import { describe, it, expect } from 'vitest'
import { ชื่อแสดงสัตว์, มีสายพันธุ์ที่ใช้ได้, รหัสสัตว์ } from './animalDisplay'

describe('ชื่อแสดงสัตว์ — ลำดับ: ชื่อจริง → สายพันธุ์ → ประเภท', () => {
  it('มีชื่อจริงและรู้สายพันธุ์ ใช้ชื่อจริง', () => {
    expect(ชื่อแสดงสัตว์({ ชื่อ: 'มะม่วง', สายพันธุ์: 'ชิวาวา', ชนิด: 'สุนัข' }))
      .toEqual({ ชื่อ: 'มะม่วง', ไม่มีชื่อ: false, ไม่ทราบสายพันธุ์: false })
  })

  it('มีชื่อจริงแต่ไม่รู้สายพันธุ์ ยังใช้ชื่อจริง แต่ระบุว่าไม่ทราบสายพันธุ์', () => {
    expect(ชื่อแสดงสัตว์({ ชื่อ: 'มะม่วง', สายพันธุ์: 'ไม่ระบุ', ชนิด: 'แมว' }))
      .toEqual({ ชื่อ: 'มะม่วง', ไม่มีชื่อ: false, ไม่ทราบสายพันธุ์: true })
  })

  it('ยังไม่ตั้งชื่อแต่รู้สายพันธุ์ ใช้สายพันธุ์เป็นหัวข้อ', () => {
    expect(ชื่อแสดงสัตว์({ ชื่อ: 'ยังไม่ตั้งชื่อ', สายพันธุ์: 'หมาไทย', ชนิด: 'สุนัข' }))
      .toEqual({ ชื่อ: 'หมาไทย', ไม่มีชื่อ: true, ไม่ทราบสายพันธุ์: false })
  })

  it('ยังไม่ตั้งชื่อและไม่รู้สายพันธุ์ ใช้ประเภทสัตว์', () => {
    expect(ชื่อแสดงสัตว์({ ชื่อ: 'ยังไม่ตั้งชื่อ', สายพันธุ์: 'ไม่ระบุ', ชนิด: 'แมว' }))
      .toEqual({ ชื่อ: 'แมว', ไม่มีชื่อ: true, ไม่ทราบสายพันธุ์: true })
  })

  it('ข้อความที่ AI ส่งกลับตอนวิเคราะห์ไม่ได้ ถือว่าไม่รู้สายพันธุ์', () => {
    expect(ชื่อแสดงสัตว์({ ชื่อ: null, สายพันธุ์: 'ไม่สามารถวิเคราะห์ได้', ชนิด: 'สุนัข' }))
      .toEqual({ ชื่อ: 'สุนัข', ไม่มีชื่อ: true, ไม่ทราบสายพันธุ์: true })
  })

  it('ไม่มีข้อมูลเลยก็ไม่ throw ใช้คำว่า สัตว์', () => {
    expect(ชื่อแสดงสัตว์({ ชื่อ: '', สายพันธุ์: null, ชนิด: undefined }).ชื่อ).toBe('สัตว์')
  })

  it('ชื่อที่เป็นช่องว่างล้วนถือว่าไม่มีชื่อ', () => {
    expect(ชื่อแสดงสัตว์({ ชื่อ: '   ', สายพันธุ์: 'บีเกิล', ชนิด: 'สุนัข' }).ไม่มีชื่อ).toBe(true)
  })

  it('ตัดช่องว่างหัวท้ายของชื่อ', () => {
    expect(ชื่อแสดงสัตว์({ ชื่อ: '  ทองแดง ', สายพันธุ์: 'บีเกิล', ชนิด: 'สุนัข' }).ชื่อ).toBe('ทองแดง')
  })
})

describe('มีสายพันธุ์ที่ใช้ได้', () => {
  it('ค่าที่ไม่ใช่สายพันธุ์จริงให้ false', () => {
    for (const ค่า of ['', '   ', null, undefined, 'ไม่ระบุ', 'ไม่สามารถวิเคราะห์ได้']) {
      expect(มีสายพันธุ์ที่ใช้ได้(ค่า)).toBe(false)
    }
  })

  it('สายพันธุ์จริงให้ true', () => {
    expect(มีสายพันธุ์ที่ใช้ได้('ไซบีเรียน ฮัสกี้')).toBe(true)
  })
})

describe('รหัสสัตว์', () => {
  it('ใช้ animals.id ตรงๆ ขึ้นต้นด้วย #', () => {
    expect(รหัสสัตว์(38)).toBe('#38')
  })
})
