// animalDisplay.js — ชื่อที่แสดงของ "สัตว์" ในหน้าผู้ใช้ (การ์ดหน้าค้นหา + หน้ารายละเอียด)
//
// สัตว์ที่เจ้าหน้าที่ยังไม่ตั้งชื่อถูกเก็บเป็น 'ยังไม่ตั้งชื่อ' ถ้าแสดงตรงๆ การ์ดทุกใบจะหัวข้อซ้ำกันหมด
// และผู้ใช้บอกเจ้าหน้าที่ไม่ได้ว่าอยากรับเลี้ยงตัวไหน ลำดับที่ใช้:
//   1) มีชื่อจริง → ใช้ชื่อ
//   2) ไม่มีชื่อแต่มีสายพันธุ์ที่ใช้ได้ → ใช้สายพันธุ์เป็นหัวข้อ
//   3) ไม่มีทั้งคู่ (AI วิเคราะห์ไม่ได้ / เจ้าหน้าที่ยังไม่กรอก) → ใช้ประเภท (สุนัข/แมว)
// และทุกใบมี "รหัสสัตว์" (animals.id) ไว้อ้างอิงตอนโทรหาศูนย์ — ฝั่งเจ้าหน้าที่แสดงรหัสเดียวกัน

const ค่าที่ไม่ใช่ชื่อ = ['', 'ยังไม่ตั้งชื่อ']
// ค่าที่แปลว่า "ไม่รู้สายพันธุ์": ว่าง / ค่าที่ FindPet ใส่ให้เอง / ข้อความที่ AI ส่งกลับตอนวิเคราะห์ไม่ได้
const ค่าที่ไม่ใช่สายพันธุ์ = ['', 'ไม่ระบุ', 'ไม่สามารถวิเคราะห์ได้']

export function มีสายพันธุ์ที่ใช้ได้(สายพันธุ์) {
  return !ค่าที่ไม่ใช่สายพันธุ์.includes((สายพันธุ์ || '').trim())
}

// คืน { ชื่อ, ไม่มีชื่อ, ไม่ทราบสายพันธุ์ }
//   ชื่อ              — ข้อความหัวข้อที่ใช้แสดง
//   ไม่มีชื่อ          — true ถ้าหัวข้อนี้ไม่ใช่ชื่อจริง (ใช้โชว์ป้าย "ยังไม่มีชื่อ" และเลือกข้อความปุ่ม)
//   ไม่ทราบสายพันธุ์    — true ถ้าไม่มีสายพันธุ์ที่ใช้ได้ (หัวข้อจึงเป็นประเภทสัตว์)
export function ชื่อแสดงสัตว์({ ชื่อ, สายพันธุ์, ชนิด }) {
  const มีชื่อจริง = !ค่าที่ไม่ใช่ชื่อ.includes((ชื่อ || '').trim())
  const รู้สายพันธุ์ = มีสายพันธุ์ที่ใช้ได้(สายพันธุ์)
  if (มีชื่อจริง)  return { ชื่อ: ชื่อ.trim(),     ไม่มีชื่อ: false, ไม่ทราบสายพันธุ์: !รู้สายพันธุ์ }
  if (รู้สายพันธุ์) return { ชื่อ: สายพันธุ์.trim(), ไม่มีชื่อ: true,  ไม่ทราบสายพันธุ์: false }
  return { ชื่อ: ชนิด || 'สัตว์', ไม่มีชื่อ: true, ไม่ทราบสายพันธุ์: true }
}

export function รหัสสัตว์(id) {
  return `#${id}`
}
