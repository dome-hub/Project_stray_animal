import { describe, it, expect, vi, afterEach } from 'vitest'
import {
  แปลงเป็นDate, วันนี้ไทย, วันที่สั้นไทย, วันเวลาเต็มไทย, ชั่วโมงที่ผ่านมา, ป้ายวันที่กลุ่มไทย,
} from './dateTime'

afterEach(() => { vi.useRealTimers() })

describe('แปลงเป็นDate — created_at จากฐานข้อมูลไม่มี timezone ต้องอ่านเป็น UTC', () => {
  it('สตริงไม่มี timezone = UTC (ต้นเหตุเวลาเพี้ยน 7 ชม. ที่เคยเกิด)', () => {
    expect(แปลงเป็นDate('2026-10-31T07:30:44.29037').toISOString()).toBe('2026-10-31T07:30:44.290Z')
  })

  it('สตริงที่มี +00:00 หรือ Z ใช้ตามนั้น', () => {
    expect(แปลงเป็นDate('2026-10-31T07:30:44+00:00').toISOString()).toBe('2026-10-31T07:30:44.000Z')
    expect(แปลงเป็นDate('2026-10-31T07:30:44Z').toISOString()).toBe('2026-10-31T07:30:44.000Z')
  })

  it('วันที่ล้วน (lost_date) ได้เที่ยงคืน UTC', () => {
    expect(แปลงเป็นDate('2026-10-31').toISOString()).toBe('2026-10-31T00:00:00.000Z')
  })

  it('ค่าว่างได้ Date ที่ไม่ถูกต้อง ไม่ throw', () => {
    expect(Number.isNaN(แปลงเป็นDate('').getTime())).toBe(true)
    expect(Number.isNaN(แปลงเป็นDate(null).getTime())).toBe(true)
  })
})

describe('แสดงเวลาเป็นเวลาไทย (+7) ไม่ขึ้นกับ timezone เครื่อง', () => {
  it('07:30 UTC แสดงเป็น 14:30 น.', () => {
    expect(วันเวลาเต็มไทย('2026-10-31T07:30:44.29037')).toContain('14:30')
  })

  it('ข้ามเที่ยงคืนไทย: 18:30 UTC ของ 31 ต.ค. = 01:30 ของวันที่ 1 พ.ย.', () => {
    const ข้อความ = วันเวลาเต็มไทย('2026-10-31T18:30:00Z')
    expect(ข้อความ).toContain('พ.ย.')
    expect(ข้อความ).toContain('01:30')
  })

  it('ปีแสดงเป็น พ.ศ.', () => {
    expect(วันที่สั้นไทย('2026-10-31T07:30:00Z')).toContain('2569')
  })

  it('ค่าว่างได้ค่าว่าง/null', () => {
    expect(วันที่สั้นไทย('')).toBe('')
    expect(วันเวลาเต็มไทย(null)).toBeNull()
  })
})

describe('วันนี้ไทย — ใช้กับ input วันที่และตรวจวันในอนาคต', () => {
  it('01:30 น. ของ 1 พ.ย. (ไทย) ต้องได้ 2026-11-01 ทั้งที่ UTC ยังเป็น 31 ต.ค.', () => {
    vi.useFakeTimers()
    vi.setSystemTime(new Date('2026-10-31T18:30:00Z'))
    expect(new Date().toISOString().slice(0, 10)).toBe('2026-10-31')   // วิธีเดิมที่ผิด
    expect(วันนี้ไทย()).toBe('2026-11-01')
  })

  it('ขอบเขตเที่ยงคืนไทย: 23:59 ยังเป็นวันเดิม 00:00 เป็นวันใหม่', () => {
    vi.useFakeTimers()
    vi.setSystemTime(new Date('2026-10-31T16:59:00Z'))   // 23:59 ไทย
    expect(วันนี้ไทย()).toBe('2026-10-31')
    vi.setSystemTime(new Date('2026-10-31T17:00:00Z'))   // 00:00 ไทย
    expect(วันนี้ไทย()).toBe('2026-11-01')
  })

  it('รูปแบบเป็น ปปปป-ดด-วว (เทียบสตริงกับค่าของ input type=date ได้)', () => {
    expect(วันนี้ไทย()).toMatch(/^\d{4}-\d{2}-\d{2}$/)
  })
})

describe('ชั่วโมงที่ผ่านมา', () => {
  it('นับจากเวลาจริง (UTC) ไม่เพี้ยน 7 ชม.', () => {
    vi.useFakeTimers()
    vi.setSystemTime(new Date('2026-10-31T10:45:00Z'))
    expect(ชั่วโมงที่ผ่านมา('2026-10-31T07:30:44.29037')).toBe(3)
  })

  it('ค่าว่างได้ 0', () => {
    expect(ชั่วโมงที่ผ่านมา('')).toBe(0)
  })
})

describe('ป้ายวันที่กลุ่มไทย', () => {
  it('วันนี้ / เมื่อวาน / วันที่เก่ากว่านั้น นับตามปฏิทินไทย', () => {
    vi.useFakeTimers()
    vi.setSystemTime(new Date('2026-10-31T05:00:00Z'))   // 12:00 ไทย วันที่ 31
    expect(ป้ายวันที่กลุ่มไทย('2026-10-31T01:00:00Z')).toMatch(/^วันนี้ \(31 /)
    expect(ป้ายวันที่กลุ่มไทย('2026-10-30T05:00:00Z')).toMatch(/^เมื่อวาน \(30 /)
    expect(ป้ายวันที่กลุ่มไทย('2026-10-20T05:00:00Z')).toBe('20 ต.ค.')
  })

  it('เวลา 18:00 UTC ของเมื่อวานที่ตรงกับ 01:00 ไทยของวันนี้ ถือเป็นวันนี้', () => {
    vi.useFakeTimers()
    vi.setSystemTime(new Date('2026-10-31T05:00:00Z'))
    expect(ป้ายวันที่กลุ่มไทย('2026-10-30T18:00:00Z')).toMatch(/^วันนี้/)
  })
})
