import { describe, it, expect } from 'vitest'
import {
  สถานะสัตว์ในความดูแล, สถานะสัตว์ออกไปแล้ว, ตัวเลือกนำสัตว์ออก, เงื่อนไขตัดสัตว์ที่ออกไปแล้ว,
} from './animalStatus'

describe('สถานะสัตว์ในศูนย์', () => {
  it('สถานะในความดูแลกับออกไปแล้วไม่ซ้อนกัน (สัตว์ตัวหนึ่งต้องอยู่ฝั่งเดียว)', () => {
    for (const สถานะ of สถานะสัตว์ออกไปแล้ว) {
      expect(สถานะสัตว์ในความดูแล).not.toContain(สถานะ)
    }
  })

  it('สถานะออกไปแล้วครบทั้ง 4: ได้บ้าน / ส่งคืนเจ้าของ / หลุดหาย / เสียชีวิต', () => {
    expect([...สถานะสัตว์ออกไปแล้ว].sort()).toEqual(
      ['มีผู้รับเลี้ยง', 'ส่งคืนเจ้าของสำเร็จ', 'สัตว์หลุดหาย', 'เสียชีวิต'].sort(),
    )
  })

  it('ตัวเลือกนำสัตว์ออกในฟอร์มเจ้าหน้าที่ ตรงกับสถานะออกไปแล้วทุกตัว ไม่ขาดไม่เกิน', () => {
    expect(ตัวเลือกนำสัตว์ออก.map((ต) => ต.value).sort()).toEqual([...สถานะสัตว์ออกไปแล้ว].sort())
  })

  it('ทุกตัวเลือกมีสีครบ และแต่ละตัวใช้สีไม่ซ้ำกัน (แยกด้วยตาได้ชัดเจน)', () => {
    for (const ต of ตัวเลือกนำสัตว์ออก) {
      expect(ต.dot).toBeTruthy()
      expect(ต.เลือก).toBeTruthy()
      expect(ต.แจ้ง).toBeTruthy()
    }
    const สีจุด = ตัวเลือกนำสัตว์ออก.map((ต) => ต.dot)
    expect(new Set(สีจุด).size).toBe(สีจุด.length)
  })

  it('เงื่อนไข PostgREST ครอบทุกสถานะที่ออกไปแล้ว ในรูปวงเล็บคั่นด้วยจุลภาค', () => {
    expect(เงื่อนไขตัดสัตว์ที่ออกไปแล้ว.startsWith('(')).toBe(true)
    expect(เงื่อนไขตัดสัตว์ที่ออกไปแล้ว.endsWith(')')).toBe(true)
    for (const สถานะ of สถานะสัตว์ออกไปแล้ว) {
      expect(เงื่อนไขตัดสัตว์ที่ออกไปแล้ว).toContain(`"${สถานะ}"`)
    }
    expect(เงื่อนไขตัดสัตว์ที่ออกไปแล้ว.split(',').length).toBe(สถานะสัตว์ออกไปแล้ว.length)
  })
})
