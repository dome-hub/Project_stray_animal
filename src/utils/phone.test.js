import { describe, it, expect } from 'vitest'
import { เบอร์ถูกต้อง, รูปแบบเบอร์โทร } from './phone'

describe('เกณฑ์เบอร์โทร (10 หลักเท่านั้น)', () => {
  it('รับเบอร์มือถือไทย 10 หลักขึ้นต้น 0', () => {
    expect(เบอร์ถูกต้อง('0812345678')).toBe(true)
    expect(เบอร์ถูกต้อง('0853948659')).toBe(true)
  })

  it('ไม่รับเบอร์ 9 หลัก (เบอร์บ้านเดิมที่เคยผ่านหน้าแจ้งสัตว์จร)', () => {
    expect(เบอร์ถูกต้อง('034351083')).toBe(false)
  })

  it('ไม่รับเบอร์ที่ยาวเกิน 10 หลัก', () => {
    expect(เบอร์ถูกต้อง('08123456789')).toBe(false)
  })

  it('ไม่รับเบอร์ที่ไม่ขึ้นต้นด้วย 0', () => {
    expect(เบอร์ถูกต้อง('1812345678')).toBe(false)
  })

  it('ไม่รับเบอร์ที่มีขีดหรือตัวอักษรปน', () => {
    expect(เบอร์ถูกต้อง('081-234-5678')).toBe(false)
    expect(เบอร์ถูกต้อง('08123456ab')).toBe(false)
  })

  it('ตัดช่องว่างหัวท้ายก่อนตรวจ', () => {
    expect(เบอร์ถูกต้อง('  0812345678 ')).toBe(true)
  })

  it('ค่าว่าง/null/undefined ไม่ผ่าน (ไม่ error)', () => {
    expect(เบอร์ถูกต้อง('')).toBe(false)
    expect(เบอร์ถูกต้อง(null)).toBe(false)
    expect(เบอร์ถูกต้อง(undefined)).toBe(false)
  })

  it('regex ที่ export ให้หน้าอื่นใช้ตรงกับฟังก์ชัน', () => {
    expect(รูปแบบเบอร์โทร.test('0812345678')).toBe(true)
    expect(รูปแบบเบอร์โทร.test('081234567')).toBe(false)
  })
})
