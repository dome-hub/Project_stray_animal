import { describe, it, expect } from 'vitest'
import {
  ช่วงซูมดิจิทัล, จำกัดซูม, ซูมจากการหยิก, ระยะห่าง, พื้นที่ครอปซูม, อ่านช่วงซูมฮาร์ดแวร์,
} from './cameraZoom'

describe('จำกัดซูม', () => {
  it('ค่าในช่วงคงเดิม เกินช่วงถูกตัดที่ขอบ', () => {
    expect(จำกัดซูม(2, 1, 4)).toBe(2)
    expect(จำกัดซูม(0.2, 1, 4)).toBe(1)
    expect(จำกัดซูม(9, 1, 4)).toBe(4)
  })
})

describe('ซูมจากการหยิก 2 นิ้ว', () => {
  it('นิ้วห่างขึ้น 2 เท่า ซูมขึ้น 2 เท่า', () => {
    expect(ซูมจากการหยิก(1, 100, 200, 1, 4)).toBe(2)
  })

  it('นิ้วเข้าหากัน ซูมลดลง แต่ไม่ต่ำกว่า min', () => {
    expect(ซูมจากการหยิก(2, 200, 100, 1, 4)).toBe(1)
    expect(ซูมจากการหยิก(1, 200, 50, 1, 4)).toBe(1)
  })

  it('ซูมไม่เกิน max', () => {
    expect(ซูมจากการหยิก(3, 100, 500, 1, 4)).toBe(4)
  })

  it('ระยะตอนเริ่มเป็น 0 หรือไม่มี ไม่หารศูนย์ ใช้ซูมเดิม', () => {
    expect(ซูมจากการหยิก(2, 0, 100, 1, 4)).toBe(2)
    expect(ซูมจากการหยิก(2, undefined, 100, 1, 4)).toBe(2)
  })
})

describe('ระยะห่างระหว่างนิ้ว', () => {
  it('คำนวณระยะ 2 จุดแบบยุคลิด', () => {
    expect(ระยะห่าง({ x: 0, y: 0 }, { x: 3, y: 4 })).toBe(5)
  })
})

describe('พื้นที่ครอปซูมดิจิทัล (ปุ่มถ่ายต้องได้ภาพตรงกับที่เห็นบนจอ)', () => {
  it('ซูม 1 เท่า ได้ทั้งเฟรม', () => {
    expect(พื้นที่ครอปซูม(1280, 720, 1)).toEqual({ sx: 0, sy: 0, sw: 1280, sh: 720 })
  })

  it('ซูม 2 เท่า ตัดตรงกลาง เหลือครึ่งหนึ่งของแต่ละด้าน', () => {
    expect(พื้นที่ครอปซูม(1280, 720, 2)).toEqual({ sx: 320, sy: 180, sw: 640, sh: 360 })
  })

  it('ซูมต่ำกว่า 1 ถือเป็น 1 (ไม่ครอปเกินเฟรม)', () => {
    expect(พื้นที่ครอปซูม(1280, 720, 0.5)).toEqual({ sx: 0, sy: 0, sw: 1280, sh: 720 })
  })

  it('ช่วงซูมดิจิทัลตั้งไว้ 1–4 เท่า', () => {
    expect(ช่วงซูมดิจิทัล).toEqual({ min: 1, max: 4, step: 0.1 })
  })
})

describe('อ่านช่วงซูมฮาร์ดแวร์', () => {
  it('กล้องรองรับซูมจริง คืนช่วง min/max', () => {
    const track = { getCapabilities: () => ({ zoom: { min: 1, max: 8 } }) }
    expect(อ่านช่วงซูมฮาร์ดแวร์(track)).toEqual({ min: 1, max: 8, step: 0.1 })
  })

  it('ไม่รองรับซูม (ไม่มี zoom ใน capabilities) คืน null เพื่อใช้ซูมดิจิทัล', () => {
    expect(อ่านช่วงซูมฮาร์ดแวร์({ getCapabilities: () => ({}) })).toBeNull()
  })

  it('ช่วงซูมที่ max ไม่มากกว่า min คืน null', () => {
    expect(อ่านช่วงซูมฮาร์ดแวร์({ getCapabilities: () => ({ zoom: { min: 1, max: 1 } }) })).toBeNull()
  })

  it('track ไม่มี getCapabilities หรือเป็น null ไม่ throw', () => {
    expect(อ่านช่วงซูมฮาร์ดแวร์({})).toBeNull()
    expect(อ่านช่วงซูมฮาร์ดแวร์(null)).toBeNull()
  })

  it('เบราว์เซอร์ที่โยน error ตอนอ่าน capabilities ถือว่าไม่รองรับ', () => {
    const track = { getCapabilities: () => { throw new Error('not supported') } }
    expect(อ่านช่วงซูมฮาร์ดแวร์(track)).toBeNull()
  })
})
