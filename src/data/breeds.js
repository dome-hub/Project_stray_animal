// ---- สังเคราะห์ระดับกิจกรรม จากคำในนิสัย ----
function ระดับกิจกรรม(นิสัย) {
  const ข้อความ = นิสัย.join(' ')
  if (/พลังงานสูงมาก|พลังงานล้นเปี่ยม/.test(ข้อความ)) return { ระดับ: 'สูงมาก', คำอธิบาย: 'ต้องพาออกกำลังกาย/เดินเล่นทุกวัน อย่างน้อยวันละ 1-2 ชั่วโมง เหมาะกับคนมีเวลาและพื้นที่' }
  if (/พลังงานสูง|ตื่นตัว|แอคทีฟ|คล่องแคล่ว|ว่องไว/.test(ข้อความ)) return { ระดับ: 'สูง', คำอธิบาย: 'ชอบวิ่งเล่น/ทำกิจกรรม ควรมีเวลาพาออกกำลังกายสม่ำเสมอ' }
  if (/สงบ|สุขุม|นิ่งสงบ|ใจเย็น|รักสงบ|เงียบสงบ/.test(ข้อความ)) return { ระดับ: 'ต่ำ', คำอธิบาย: 'อารมณ์นิ่ง ไม่ต้องการกิจกรรมหนัก เหมาะกับพื้นที่จำกัดหรือคอนโด' }
  return { ระดับ: 'ปานกลาง', คำอธิบาย: 'ต้องการเวลาเล่น/เดินเล่นพอประมาณในแต่ละวัน' }
}

// ---- สังเคราะห์คำแนะนำการดูแลขน ----
function การดูแลขน(สายพันธุ์) {
  if (สายพันธุ์.id === 'sphynx') return 'ไม่มีขน ต้องเช็ดผิวหนังสม่ำเสมอและระวังเรื่องอุณหภูมิ'
  if (สายพันธุ์.ขนยาว) return 'ขนยาว/หนา ควรแปรงขนทุกวันเพื่อไม่ให้พันกัน และหมั่นตรวจเห็บหมัด'
  if (สายพันธุ์.ประเภท === 'แมว') return 'ขนสั้น ดูแลง่าย แปรงขนสัปดาห์ละ 1-2 ครั้งก็เพียงพอ'
  return 'ขนสั้น-กลาง แปรงขนสัปดาห์ละ 2-3 ครั้ง อาบน้ำตามความเหมาะสม'
}

// ---- สังเคราะห์คำแนะนำว่าเหมาะกับใคร ----
function เหมาะกับใคร(สายพันธุ์, กิจกรรม) {
  const ประโยค = []
  if (กิจกรรม.ระดับ === 'สูงมาก' || กิจกรรม.ระดับ === 'สูง') {
    ประโยค.push('คนที่มีเวลาพาออกกำลังกาย/เล่นด้วยเป็นประจำ')
  } else {
    ประโยค.push('คนที่มีเวลาไม่มาก หรืออาศัยอยู่ในพื้นที่จำกัดอย่างคอนโด')
  }
  if (สายพันธุ์.ขนาด === 'ใหญ่' || สายพันธุ์.ขนาด === 'ใหญ่มาก') {
    ประโยค.push('บ้านที่มีพื้นที่กว้างพอสมควร')
  } else {
    ประโยค.push('บ้านหรือคอนโดขนาดเล็กก็เลี้ยงได้')
  }
  if (สายพันธุ์.นิสัย.some((n) => /เป็นมิตร|ร่าเริง|ใจดี|เชื่องมาก/.test(n))) {
    ประโยค.push('ครอบครัวที่มีเด็กหรือสัตว์เลี้ยงตัวอื่น')
  }
  return ประโยค
}

export const สายพันธุ์ทั้งหมด = สายพันธุ์ดิบ.map((b) => {
  const กิจกรรม = ระดับกิจกรรม(b.นิสัย)
  return {
    ...b,
    กิจกรรม,
    ดูแลขน: การดูแลขน(b),
    เหมาะกับ: เหมาะกับใคร(b, กิจกรรม),
  }
})
